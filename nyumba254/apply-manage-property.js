if (missing.length) die('dashboard.html does not look like the expected file. Missing: ' + missing.join(', '));
if (!/src=["']\/?dashboard\.js/i.test(html)) die('No /dashboard.js script tag found in ' + htmlName + '.');

try {
  new vm.Script(RUNTIME, { filename: RUNTIME_FILE });
} catch (e) {
  die('Generated runtime failed its syntax check (nothing was written): ' + e.message);
}

const hash = crypto.createHash('sha1').update(RUNTIME).digest('hex').slice(0, 10);
const tag = '<script src="/' + RUNTIME_FILE + '?v=' + hash + '"></script>';
const block = MARK_START + eol + tag + eol + MARK_END;

let base2 = html.replace(blockRe, '');
const patchTag = /<script\b[^>]*\bsrc=["']\/?patch\.js(?:\?[^"']*)?["'][^>]*>\s*<\/script>/i;
let out;
const m = base2.match(patchTag);
if (m) {
  out = base2.replace(patchTag, (full) => full + eol + block);
} else if (/<\/body>/i.test(base2)) {
  log('Note: /patch.js tag not found - inserting before </body>.');
  out = base2.replace(/<\/body>/i, block + eol + '</body>');
} else {
  die('Could not find /patch.js or </body> to anchor the script tag.');
}

const prevRuntime = fs.existsSync(runtimePath) ? fs.readFileSync(runtimePath, 'utf8') : null;
const unchanged = out === html && prevRuntime === RUNTIME;

log('Target html : ' + htmlPath);
log('Runtime file: ' + runtimePath + (prevRuntime === null ? '  (new)' : prevRuntime === RUNTIME ? '  (unchanged)' : '  (will be replaced)'));
log('Script tag  : ' + tag);
if (!fs.existsSync(path.join(outDir, 'dashboard.js'))) log('Warning     : dashboard.js not found beside the html (fine if served from elsewhere).');
if (unchanged) { log('\nAlready up to date. Nothing to do.'); process.exit(0); }
if (dry) { log('\n(dry run - nothing written)'); process.exit(0); }

if (!fs.existsSync(backupPath)) { fs.copyFileSync(htmlPath, backupPath); log('Backup      : ' + backupPath); }
writeAtomic(runtimePath, RUNTIME);
writeAtomic(htmlPath, out);

const verify = fs.readFileSync(htmlPath, 'utf8');
const count = (verify.match(new RegExp(escapeRe(MARK_START), 'g')) || []).length;
if (count !== 1) die('Post-write check failed: expected 1 patch block, found ' + count + '. Restore from ' + backupPath);

log('\nDone. Deploy these two files:\n  - ' + path.basename(htmlPath) + '\n  - ' + RUNTIME_FILE);
log('Then hard-refresh the dashboard (Ctrl/Cmd+Shift+R).');
log('Undo any time with: node ' + path.basename(__filename) + ' --revert');